package com.example.blackclover;

public class Personaje {

    String nombre;
    String magia;
    String rango;
    String escuadron;
    String descripcion;
    int imagen;

    public Personaje(String nombre, String magia, String rango, String escuadron, String descripcion, int imagen) {
        this.nombre = nombre;
        this.magia = magia;
        this.rango = rango;
        this.escuadron = escuadron;
        this.descripcion = descripcion;
        this.imagen = imagen;
    }
}
